#!/system/bin/sh
# ===========================================================================
# 用 MT 管理器点这个文件 → 执行 → 选「以 root 身份执行」
# 作用：停止抓取，并把日志导出到 Download/崩溃日志_时间.txt
# ===========================================================================
D=${0%/*}
cd "$D" 2>/dev/null
if [ -f "$D/logcatch.sh" ]; then
  sh "$D/logcatch.sh" stop
else
  echo "找不到 logcatch.sh（模块目录：$D）"
fi
