#!/system/bin/sh
# ===========================================================================
# 用 MT 管理器点这个文件 → 执行 → 选「以 root 身份执行」
# 作用：开始抓日志（后台记录，正常用手机即可）
#
# 为什么要单独放一个文件：Magisk 没有「操作」按钮，
# 而 WebUI 可能正好在闪退、点不进去 —— 这个文件不依赖任何界面。
# ===========================================================================
D=${0%/*}
cd "$D" 2>/dev/null
if [ -f "$D/logcatch.sh" ]; then
  sh "$D/logcatch.sh" start
else
  echo "找不到 logcatch.sh（模块目录：$D）"
fi
echo
echo "（要停止并导出：执行「抓日志-停止导出.sh」）"
